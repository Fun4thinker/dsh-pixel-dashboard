/** Standalone fallback for older dashboards and pure rendering. Missing locale defaults to zh. */
export function subscriptionValueText(locale, key, params) {
  const language = typeof locale === 'string' && locale !== ''
    ? locale.toLowerCase().split(/[-_]/)[0] : 'zh'
  const dict = language === 'zh' ? SUBSCRIPTION_VALUE_MESSAGES.zh : SUBSCRIPTION_VALUE_MESSAGES.en
  const fullKey = key.startsWith(PREFIX) ? key : PREFIX + key
  const text = dict[fullKey] ?? key
  return params === undefined ? text : text.replace(/\{(\w+)\}/g,
    (placeholder, name) => Object.hasOwn(params ?? {}, name) ? String(params[name]) : placeholder)
}
